function buildPerimeter(halfW, halfD, wallH = 6.2, mat = 'perimeter') {
  return [
    makeBox(0, 0, -(halfD + 0.8), halfW * 2 + 3, wallH, 1.6, mat, 'perimeter'),
    makeBox(0, 0, halfD + 0.8, halfW * 2 + 3, wallH, 1.6, mat, 'perimeter'),
    makeBox(-(halfW + 0.8), 0, 0, 1.6, wallH, halfD * 2 + 3, mat, 'perimeter'),
    makeBox(halfW + 0.8, 0, 0, 1.6, wallH, halfD * 2 + 3, mat, 'perimeter'),
  ];
}

