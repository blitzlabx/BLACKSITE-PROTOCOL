export function makeBox(x, y, z, w, h, d, material = 'wall', tag = 'wall', blocksSight = true) {
  return {
    x,
    y,
    z,
    w,
    h,
    d,
    minX: x - w * 0.5,
    maxX: x + w * 0.5,
    minY: y,
    maxY: y + h,
    minZ: z - d * 0.5,
    maxZ: z + d * 0.5,
    material,
    tag,
    blocksSight,
  };
}

